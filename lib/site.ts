import type { Metadata } from 'next';

/**
 * Central site configuration used across metadata, sitemap, robots and JSON-LD.
 *
 * `SITE_URL` is intentionally environment driven. There is no production
 * domain yet, so it falls back to the local dev server (which is also exposed
 * on the LAN). Set `NEXT_PUBLIC_APP_URL` to the real domain at launch time.
 */
const rawUrl =
  process.env.NEXT_PUBLIC_APP_URL ||
  (process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : '') ||
  'https://ng.ab-labs.cv';

/** Normalized absolute site origin with no trailing slash. */
export const SITE_URL = rawUrl.replace(/\/+$/, '');

export const SITE_NAME = 'aB Labs';

export const SITE_DESCRIPTION =
  'Production-ready website designs and bespoke web engineering built for ambitious Nigerian and African businesses. Mobile-first, fast customization, and ultra-fast.';

export const SITE_TAGLINE = 'Premium Website Templates & Web Agency';

export const SITE_LOCALE = 'en_NG';

export const SITE_EMAIL = 'hello@ab-labs.cv';

export const SITE_TWITTER = '@ablabs_ng';

/** Absolute URL helper for canonicals, OG images and JSON-LD. */
export function absoluteUrl(path = '/'): string {
  const normalized = path.startsWith('/') ? path : `/${path}`;
  return `${SITE_URL}${normalized}`;
}

/** Shared Open Graph image descriptor (generated by app/opengraph-image.tsx). */
export const DEFAULT_OG_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: `${SITE_NAME} — ${SITE_TAGLINE}`,
};

type OgType = 'website' | 'article' | 'product' | 'profile';

interface PageMetadataOptions {
  /** Bare title — the root layout template appends "| aB Labs". */
  title: string;
  description?: string;
  /** Route path used for the canonical URL and og:url. */
  path: string;
  image?: { url: string; width?: number; height?: number; alt?: string };
  type?: OgType;
  publishedTime?: string;
  modifiedTime?: string;
  noIndex?: boolean;
}

/**
 * Builds consistent per-page metadata (canonical, Open Graph, Twitter).
 * Root-level `metadataBase` turns the relative paths into absolute URLs.
 */
export function pageMetadata({
  title,
  description = SITE_DESCRIPTION,
  path,
  image = DEFAULT_OG_IMAGE,
  type = 'website',
  publishedTime,
  modifiedTime,
  noIndex,
}: PageMetadataOptions): Metadata {
  const fullTitle = `${title} | ${SITE_NAME}`;

  const openGraph: Metadata['openGraph'] = {
    type: type === 'product' ? 'website' : type,
    url: path,
    siteName: SITE_NAME,
    locale: SITE_LOCALE,
    title: fullTitle,
    description,
    images: [image],
    ...(publishedTime ? { publishedTime } : {}),
    ...(modifiedTime ? { modifiedTime } : {}),
  };

  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph,
    twitter: {
      card: 'summary_large_image',
      site: SITE_TWITTER,
      creator: SITE_TWITTER,
      title: fullTitle,
      description,
      images: [image.url],
    },
    ...(noIndex ? { robots: { index: false, follow: false } } : {}),
  };
}

